const STAT_LABEL_KEYS = { mine: 'sMine', classMean: 'sClassMean', rank: 'sRank', count: 'sCount', median: 'sMedian', sd: 'sSd' } as const;

/** 編輯器畫面上的區塊種類名稱（輸出文件仍用 editor/types.ts 的繁中 KIND_NAMES）。 */
export const kindNameUi = (kind: keyof typeof KIND_KEYS): string => ed()[KIND_KEYS[kind]];
/** 摘要數字的顯示名稱（編輯器畫面用）。 */
export const statLabelUi = (k: keyof typeof STAT_LABEL_KEYS): string => ed()[STAT_LABEL_KEYS[k]];
/** 區塊名稱：使用者自訂標籤優先，否則依介面語言的種類名稱。 */
export const blockNameUi = (b: { label?: string | undefined; kind: keyof typeof KIND_KEYS }): string => b.label ?? kindNameUi(b.kind);
